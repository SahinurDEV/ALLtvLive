const DICTS: Record<Lang, Record<MessageKey, string>> = { en, bn };

const listeners = new Set<() => void>();

function read(): Lang {
  if (typeof window === "undefined") return "en";
  const v = localStorage.getItem(KEY);
  return v === "bn" ? "bn" : "en";
}

export function setLang(lang: Lang) {
  try {
    localStorage.setItem(KEY, lang);
  } catch {
    // ignore
  }
  if (typeof document !== "undefined") document.documentElement.lang = lang;
  listeners.forEach((l) => l());
}

function subscribe(cb: () => void) {
  listeners.add(cb);
  return () => listeners.delete(cb);
}

export function useLang(): Lang {
  const lang = useSyncExternalStore(subscribe, read, () => "en" as Lang);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  return lang;
}

/** `const t = useT(); t("nav.home")` */
export function useT() {
  const lang = useLang();
  return useCallback(
    (key: MessageKey, vars?: Record<string, string | number>) => {
      let msg: string = DICTS[lang][key] ?? en[key];
      if (vars) for (const [k, v] of Object.entries(vars)) msg = msg.replace(`{${k}}`, String(v));
      return msg;
    },
    [lang]
  );
}

/** Locale for numbers and dates in the current language (Bangla digits in bn). */
export function localeFor(lang: Lang): string {
  return lang === "bn" ? "bn-BD" : "en-US";
}

/** Formats a number with the current language's digits. */
export function useFormatNumber() {
  const lang = useLang();
  return useCallback((n: number) => n.toLocaleString(localeFor(lang)), [lang]);
}
